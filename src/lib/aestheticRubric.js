export function clampScore(n) {
  const v = Number(n);
  if (v >= 2) return 2;
  if (v >= 1) return 1;
  return 0;
}

export function parseRubricScoresJson(raw, keys) {
  const text = String(raw || '').trim();
  const match = text.match(/\{[\s\S]*\}/);
  if (!match) return null;
  try {
    const obj = JSON.parse(match[0]);
    const out = {};
    for (const key of keys) {
      if (obj[key] === undefined) return null;
      out[key] = clampScore(obj[key]);
    }
    return out;
  } catch {
    return null;
  }
}

export function markFromAestheticQ2Score(score) {
  if (score === 2) return '✓';
  if (score === 1) return '△';
  return '✗';
}

export function markFromAestheticQ3Score(score) {
  return markFromAestheticQ2Score(score);
}

export function markFromAestheticPath(path) {
  if (path === 'A') return '✓';
  if (path === 'B' || path === 'C') return '△';
  return '✗';
}

